"""
Template report builder - builds final portfolio report from computed facts.
Minimal implementation that uses existing advisor outputs.
"""
from __future__ import annotations
from typing import Dict, Any
from pathlib import Path
import json

def build_client_report_from_template(
    cas_holdings: list,
    risk_score: int,
    goals_allocation: dict,
    fee_bleed: dict = None,
    overlap_matrix: list = None,
    saa_drift: dict = None,
    cash_plan: dict = None,
    client_name: str = "Client",
    template_path: str = None
) -> str:
    """
    Build a markdown report from computed portfolio facts.
    Uses the same structure as advisor.py outputs.
    """
    lines = [
        f"# Portfolio Review & Action Plan",
        f"",
        f"**Prepared for:** {client_name}  |  **Report Date:** Auto-generated",
        f"",
        f"---",
        f"",
        f"## 1. Portfolio Overview",
        f"",
        f"- Total Holdings: {len(cas_holdings)} funds",
        f"- Total Value: ₹{sum(h.get('value', 0) for h in cas_holdings):,.0f}",
        f"- Risk Score: {risk_score}/40",
        f"",
        f"## 2. Risk Profile",
        f"",
        f"- Risk Bucket: {_risk_bucket_from_score(risk_score)}",
        f"- Score: {risk_score}/40",
        f"",
        f"## 3. Goal Allocation",
        f"",
    ]
    
    for goal, amount in goals_allocation.items():
        lines.append(f"- **{goal}**: ₹{amount:,.0f}/month")
    
    lines.extend([
        f"",
        f"## 4. Fee Bleed Analysis",
        f"",
    ])
    
    if fee_bleed:
        lines.extend([
            f"- Regular Plans: {fee_bleed.get('n_funds', 0)} funds",
            f"- Regular Value: ₹{fee_bleed.get('regular_value', 0):,.0f}",
            f"- Annual Commission Drag: ₹{fee_bleed.get('annual_bleed', 0):,.0f}/yr",
            f"",
        ])
    
    lines.extend([
        f"## 5. Overlap Analysis",
        f"",
    ])
    
    if overlap_matrix:
        lines.append(f"- Average Overlap: {sum(p.get('pct', 0) for p in overlap_matrix)/max(1, len(overlap_matrix)):.1f}%")
        for p in overlap_matrix[:5]:
            lines.append(f"- {p.get('a', '')} vs {p.get('b', '')}: {p.get('pct', 0):.1f}%")
    
    lines.extend([
        f"",
        f"## 6. SAA Drift",
        f"",
    ])
    
    if saa_drift:
        lines.extend([
            f"- Current Equity: {saa_drift.get('current', {}).get('large', 0) + saa_drift.get('current', {}).get('mid_small', 0):.1f}%",
            f"- Target Equity: {saa_drift.get('target', {}).get('large', 0) + saa_drift.get('target', {}).get('mid_small', 0):.1f}%",
            f"- Breach: {', '.join(saa_drift.get('breach', [])) or 'None'}",
            f"",
        ])
    
    lines.extend([
        f"---",
        f"*Report generated by Fiduciary Advisor Engine*",
    ])
    
    return "\n".join(lines)

def _risk_bucket_from_score(score: int) -> str:
    if score <= 15: return "Conservative"
    elif score <= 22: return "Conservative Moderate"
    elif score <= 28: return "Balanced"
    elif score <= 34: return "Growth"
    else: return "Aggressive"